// Writes Watch/BodyPaths.swift from server/lib/bodymap.js — the body-map artwork the wall and the phone
// draw, as path strings the watch draws natively. Run it again whenever that artwork changes; nothing
// else keeps the two in step.
//
//   node apps/tools/gen-body.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const svg = createRequire(import.meta.url)(join(here, '../../server/lib/bodymap.js'));
const paths = [...svg.matchAll(/<path data-r="([^"]+)" d="([^"]+)"\/>/g)].map((m) => [m[1], m[2]]);
if (!paths.length) throw new Error('no paths found in bodymap.js');
const q = (s) => JSON.stringify(s);
const out = `// GENERATED by apps/tools/gen-body.mjs from server/lib/bodymap.js. Do not edit by hand — change the
// artwork there and run the generator.
//
// The whole figure is one 72x93 drawing: the front in x 0-36, the back in x 36-72.
let bodyPaths: [(id: String, d: String)] = [
${paths.map(([id, d]) => `    (${q(id)}, ${q(d)}),`).join('\n')}
]
`;
writeFileSync(join(here, '../Watch/BodyPaths.swift'), out);
console.log(`wrote ${paths.length} paths`);
