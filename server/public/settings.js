// Settings panel (the navbar gear). Reads/writes the shared app_settings via /api/settings.
// Routing is fixed — every voice turn runs on Opus — so there are no model/route pickers here. Each control saves on change; no explicit save button.

async function save(key, value) {
  try {
    await fetch('/api/settings', {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ key, value: String(value) }),
    });
  } catch (_) {}
}

export async function open() {
  let cur = {};
  try { cur = await (await fetch('/api/settings')).json(); } catch (_) {}
  const sil = (k, d) => { const n = parseFloat(cur[k]); return Number.isFinite(n) && n > 0 ? n : d; };
  const wrOn = !['0', 'false', 'off', 'no'].includes(String(cur.weight_reminder_enabled ?? '1').toLowerCase());
  const wrMode = cur.weight_reminder_mode === 'dynamic' ? 'dynamic' : 'manual';
  const wrTime = /^\d{2}:\d{2}$/.test(cur.weight_reminder_time || '') ? cur.weight_reminder_time : '08:00';
  const surplusVal = Number.isFinite(parseInt(cur.surplus_cal, 10)) ? parseInt(cur.surplus_cal, 10) : 150;
  const maintDays = (() => { const n = parseInt(cur.maintenance_min_days, 10); return Number.isFinite(n) && n >= 7 ? n : 14; })();
  const wfOn = ['1', 'true', 'on', 'yes'].includes(String(cur.wakefree_enabled ?? '0').toLowerCase());
  const agentOn = ['1', 'true', 'on', 'yes'].includes(String(cur.agent_mode ?? '0').toLowerCase());
  const injectOn = ['1', 'true', 'on', 'yes'].includes(String(cur.voice_inject_mode ?? '0').toLowerCase());
  const speakOn = ['1', 'true', 'on', 'yes'].includes(String(cur.voice_speak_replies ?? '0').toLowerCase());
  const pushOn = !['0', 'false', 'off', 'no'].includes(String(cur.push_enabled ?? '1').toLowerCase());
  const speechMode = String(cur.watch_speech_mode ?? 'fixed');
  // The watch edge: numbers that may be 0 (the band), and colours as #rrggbb pickers.
  const num = (k, d) => { const n = parseFloat(cur[k]); return Number.isFinite(n) && n >= 0 ? n : d; };
  const colour = (label, k, d) => '<label class="settings-row"><span>' + label + '</span>' +
    '<input class="settings-color" type="color" data-key="' + k + '" value="' +
    (/^#[0-9a-f]{6}$/i.test(cur[k] || '') ? cur[k] : d) + '"></label>';
  const jaredbotOn = ['1', 'true', 'on', 'yes'].includes(String(cur.jaredbot_enabled ?? '0').toLowerCase());
  const agentCwdRaw = cur.agent_cwd || '';
  const resetMin = (() => { const s = parseFloat(cur.session_reset_s); return Number.isFinite(s) && s > 0 ? Math.round(s / 60) : 5; })();
  // Working-directory picker: options are the repo dirs the worker publishes (agent_cwd_options).
  let cwdOpts = []; try { cwdOpts = JSON.parse(cur.agent_cwd_options || '[]'); } catch (_) {}
  if (!Array.isArray(cwdOpts)) cwdOpts = [];
  const hesc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  const cwdLabel = (p) => p.split('/').filter(Boolean).pop() || p;
  const cwdAll = cwdOpts.slice();
  if (agentCwdRaw && !cwdAll.includes(agentCwdRaw)) cwdAll.unshift(agentCwdRaw);  // keep a stale/custom value visible
  const cwdOptsHtml = '<option value=""' + (agentCwdRaw ? '' : ' selected') + '>Home (~)</option>' +
    cwdAll.map((p) => '<option value="' + hesc(p) + '"' + (p === agentCwdRaw ? ' selected' : '') + '>' + hesc(cwdLabel(p)) + '</option>').join('');
  // The alarm tones, generated by server/tools/make-alarms.py. Slug -> what it sounds like, since
  // the name alone does not tell you whether it is a siren or a lullaby.
  const TONES = [
    ['classic', 'Classic'], ['radar', 'Radar'], ['pulse', 'Pulse'],
    ['sunrise', 'Sunrise'], ['ripple', 'Ripple'], ['bells', 'Bells'], ['tide', 'Tide'],
  ];
  const VOICES = ['hannah', 'autumn', 'diana', 'austin', 'daniel', 'troy'];
  const voiceCur = VOICES.includes(cur.tts_voice) ? cur.tts_voice : 'hannah';
  const voiceOptsHtml = VOICES.map((v) =>
    '<option value="' + v + '"' + (v === voiceCur ? ' selected' : '') + '>' + v[0].toUpperCase() + v.slice(1) + '</option>').join('');
  const SPEEDS = ['1', '1.1', '1.2', '1.3', '1.4', '1.5'];
  const speedCur = SPEEDS.includes(String(cur.tts_speed)) ? String(cur.tts_speed) : '1.2';
  const speedOptsHtml = SPEEDS.map((v) =>
    '<option value="' + v + '"' + (v === speedCur ? ' selected' : '') + '>' + v + '×</option>').join('');
  const toneCur = TONES.some(([v]) => v === cur.alarm_sound) ? cur.alarm_sound : 'classic';
  const toneOptsHtml = TONES.map(([v, label]) =>
    '<option value="' + v + '"' + (v === toneCur ? ' selected' : '') + '>' + label + '</option>').join('');
  // The surf alarm's wind veto (server.js surfVeto): 0 turns it off, so it is read and saved on its
  // own rather than through the positive-only numbers below.
  const vetoKts = (() => { const n = parseFloat(cur.surf_veto_kts); return Number.isFinite(n) && n >= 0 ? n : 8; })();
  const wfThresh = sil('voiceid_threshold', 0.30);
  const wfPause = sil('wakefree_pause_s', 2);

  const back = document.createElement('div');
  back.className = 'settings-back';
  back.innerHTML =
    '<div class="settings-panel" role="dialog" aria-modal="true">' +
      '<div class="settings-h"><h3>Settings</h3><button class="settings-x" type="button" aria-label="Close">✕</button></div>' +

      '<div class="settings-sec">Full agent mode</div>' +
      '<div class="settings-seg" id="set-agent-mode">' +
        '<button type="button" data-v="0"' + (agentOn ? '' : ' class="on"') + '>Off</button>' +
        '<button type="button" data-v="1"' + (agentOn ? ' class="on"' : '') + '>On</button>' +
      '</div>' +
      '<label class="settings-row"><span>Working directory</span>' +
        '<select class="settings-text" id="set-agent-cwd">' + cwdOptsHtml + '</select></label>' +

      '<div class="settings-sec">Alarm sound</div>' +
      '<label class="settings-row"><span>Tone</span>' +
        '<select class="settings-text" id="set-alarm-sound">' + toneOptsHtml + '</select></label>' +
      '<div class="settings-row"><span>Preview</span>' +
        '<button class="settings-text" type="button" id="set-alarm-play">Play</button></div>' +
      '<label class="settings-row"><span>Onshore wind veto (kt)</span>' +
        '<input class="settings-num" type="number" step="1" min="0" max="30" inputmode="numeric" id="set-veto-kts" value="' + vetoKts + '"></label>' +

      '<div class="settings-sec">Session</div>' +
      '<label class="settings-row"><span>Idle reset (minutes)</span>' +
        '<input class="settings-num" type="number" min="1" max="240" step="1" inputmode="numeric" id="set-reset-min" value="' + resetMin + '"></label>' +

      '<div class="settings-sec">Trailing silence (seconds)</div>' +
      row('Phone', 'phone_silence_s', sil('phone_silence_s', 3)) +
      row('Watch', 'watch_silence_s', sil('watch_silence_s', 3)) +
      row('ESP (Hey&nbsp;Rhasspy)', 'esp_silence_s', sil('esp_silence_s', 3)) +
      row('Mac', 'mac_silence_s', sil('mac_silence_s', 3)) +

      // The Hub Quick complication's hard cap (Capture.swift `quickCap`): seconds from the microphone
      // opening, after which the command sends whatever it has, silence or not.
      '<div class="settings-sec">Watch: quick command</div>' +
      '<label class="settings-row"><span>Cutoff (s)</span>' +
        '<input class="settings-num" type="number" min="1" max="30" step="0.5" inputmode="decimal" ' +
        'data-key="watch_quick_s" value="' + sil('watch_quick_s', 5) + '"></label>' +

      // What counts as his voice on the watch (Capture.swift `Endpointer`): a FIXED lowest level, a
      // line that follows the ROOM, so many times its quietest level, or VOICE — Apple's on-device sound
      // classifier (`VoiceDetector`), where only speech counts and a snap or a door does not.
      '<div class="settings-sec">Watch: speech line</div>' +
      '<div class="settings-seg" id="set-speech-mode">' +
        ['fixed', 'room', 'voice'].map((v) => '<button type="button" data-v="' + v + '"' +
          ((speechMode === v || (v === 'fixed' && !['room', 'voice'].includes(speechMode))) ? ' class="on"' : '') + '>' +
          v[0].toUpperCase() + v.slice(1) + '</button>').join('') +
      '</div>' +
      '<label class="settings-row"><span>Fixed</span>' +
        '<input class="settings-num" type="number" min="0.001" max="0.1" step="0.001" inputmode="decimal" ' +
        'data-key="watch_speech_min" value="' + sil('watch_speech_min', 0.02) + '"></label>' +
      '<label class="settings-row"><span>Room ×</span>' +
        '<input class="settings-num" type="number" min="1" max="50" step="0.5" inputmode="decimal" ' +
        'data-key="watch_speech_ratio" value="' + sil('watch_speech_ratio', 8) + '"></label>' +
      '<label class="settings-row"><span>Voice ≥</span>' +
        '<input class="settings-num" type="number" min="0.05" max="0.95" step="0.05" inputmode="decimal" ' +
        'data-key="watch_voice_min" value="' + sil('watch_voice_min', 0.5) + '"></label>' +

      // How a reply sounds when it is read aloud: the voice is the server's (`lib/speech.js`), shared by
      // the phone and the watch.
      '<div class="settings-sec">Watch voice</div>' +
      '<label class="settings-row"><span>Voice</span>' +
        '<select class="settings-text" id="set-tts-voice">' + voiceOptsHtml + '</select></label>' +
      '<label class="settings-row"><span>Speed</span>' +
        '<select class="settings-text" id="set-tts-speed">' + speedOptsHtml + '</select></label>' +

      '<div class="settings-sec">Watch edge</div>' +
      '<label class="settings-row"><span>Line (px)</span>' +
        '<input class="settings-num" type="number" min="1" max="8" step="1" inputmode="numeric" ' +
        'data-key="watch_border_px" value="' + num('watch_border_px', 3) + '"></label>' +
      '<label class="settings-row"><span>Black band (px)</span>' +
        '<input class="settings-num" type="number" min="0" max="8" step="1" inputmode="numeric" data-min0 ' +
        'data-key="watch_border_band_px" value="' + num('watch_border_band_px', 2) + '"></label>' +
      colour('Recording', 'watch_border_recording', '#f2a13d') +
      colour('Locked', 'watch_border_locked', '#e5484d') +
      colour('Working', 'watch_border_working', '#ffffff') +
      colour('Working ring', 'watch_border_ring', '#404040') +
      colour('Listening', 'watch_border_listening', '#295bac') +

      '<div class="settings-sec">Uploaded clips must sound like you</div>' +
      '<label class="settings-row"><span>Watch / phone listening<br><small>0 = accept anything</small></span>' +
        '<input class="settings-num" type="number" min="0" max="0.9" step="0.01" inputmode="decimal" ' +
        'data-key="voice_upload_accept" value="' + sil('voice_upload_accept', 0.22) + '"></label>' +

      '<div class="settings-sec">Always-on voice (wake-free)</div>' +
      '<div class="settings-seg" id="set-wf-enabled">' +
        '<button type="button" data-v="0"' + (wfOn ? '' : ' class="on"') + '>Off</button>' +
        '<button type="button" data-v="1"' + (wfOn ? ' class="on"' : '') + '>On</button>' +
      '</div>' +
      '<label class="settings-row"><span>Voice-match threshold<br><small>lower = more permissive</small></span>' +
        '<input class="settings-num" type="number" min="0.1" max="0.9" step="0.05" inputmode="decimal" data-key="voiceid_threshold" value="' + wfThresh + '"></label>' +
      '<label class="settings-row"><span>End-of-command pause (s)<br><small>ESP fallback only — wake-free ends on your voice</small></span>' +
        '<input class="settings-num" type="number" min="0.5" max="6" step="0.5" inputmode="decimal" data-key="wakefree_pause_s" value="' + wfPause + '"></label>' +

      '<div class="settings-sec">Voice inject mode</div>' +
      '<div class="settings-seg" id="set-inject-mode">' +
        '<button type="button" data-v="0"' + (injectOn ? '' : ' class="on"') + '>Off</button>' +
        '<button type="button" data-v="1"' + (injectOn ? ' class="on"' : '') + '>On</button>' +
      '</div>' +

      '<div class="settings-sec">Speak replies aloud</div>' +
      '<div class="settings-seg" id="set-speak-replies">' +
        '<button type="button" data-v="0"' + (speakOn ? '' : ' class="on"') + '>Off</button>' +
        '<button type="button" data-v="1"' + (speakOn ? ' class="on"' : '') + '>On</button>' +
      '</div>' +
      '<div class="settings-sec">Push notifications</div>' +
      '<div class="settings-seg" id="set-push">' +
        '<button type="button" data-v="0"' + (pushOn ? '' : ' class="on"') + '>Off</button>' +
        '<button type="button" data-v="1"' + (pushOn ? ' class="on"' : '') + '>On</button>' +
      '</div>' +
      '<div class="settings-sec">JaredBot</div>' +
      '<div class="settings-seg" id="set-jaredbot">' +
        '<button type="button" data-v="0"' + (jaredbotOn ? '' : ' class="on"') + '>Off</button>' +
        '<button type="button" data-v="1"' + (jaredbotOn ? ' class="on"' : '') + '>On</button>' +
      '</div>' +

      '<div class="settings-sec">Weight reminder</div>' +
      '<div class="settings-seg" id="set-wr-enabled">' +
        '<button type="button" data-v="0"' + (wrOn ? '' : ' class="on"') + '>Off</button>' +
        '<button type="button" data-v="1"' + (wrOn ? ' class="on"' : '') + '>On</button>' +
      '</div>' +
      '<div class="settings-seg" id="set-wr-mode" style="margin-top:8px">' +
        '<button type="button" data-v="manual"' + (wrMode === 'manual' ? ' class="on"' : '') + '>Manual</button>' +
        '<button type="button" data-v="dynamic"' + (wrMode === 'dynamic' ? ' class="on"' : '') + '>Dynamic</button>' +
      '</div>' +
      '<label class="settings-row' + (wrMode === 'dynamic' ? ' dim' : '') + '" id="set-wr-time-row"><span>Time</span>' +
        '<input class="settings-time" type="time" id="set-wr-time" value="' + wrTime + '"' + (wrMode === 'dynamic' ? ' disabled' : '') + '></label>' +

      '<div class="settings-sec">Nutrition goal</div>' +
      '<label class="settings-row"><span>Surplus / deficit (kcal)<br><small>+ to bulk, − to cut, 0 = maintenance</small></span>' +
        '<input class="settings-num" type="number" step="10" min="-1000" max="1000" inputmode="numeric" id="set-surplus" value="' + surplusVal + '"></label>' +

      '<div class="settings-sec">Adaptive maintenance</div>' +
      '<label class="settings-row"><span>Calibration window (days)<br><small>aligned logging days before the goal adapts</small></span>' +
        '<input class="settings-num" type="number" step="1" min="7" max="60" inputmode="numeric" data-key="maintenance_min_days" value="' + maintDays + '"></label>' +
    '</div>';
  document.body.appendChild(back);

  // THE VOICE SYSTEM — the mics and the routing — sits at the bottom of Settings on the phone's home
  // page (#voicesys there). It is MOVED in for as long as the panel is open and put back on close, so
  // its cards keep rendering on every frame like any other; a page without it has nothing to move.
  const vs = document.getElementById('voicesys');
  const vsAt = vs ? document.createComment('voicesys') : null;
  if (vs) { vs.before(vsAt); back.querySelector('.settings-panel').appendChild(vs); }
  const close = () => { if (vs) vsAt.replaceWith(vs); back.remove(); };
  back.addEventListener('click', (e) => { if (e.target === back) close(); });
  // Picking a tone previews it: choosing an alarm you have not heard is choosing blind, and this is
  // the only place it can be auditioned before 7am. One element reused, so a second press replaces
  // the first rather than layering.
  let preview = null;
  const playTone = () => {
    const slug = back.querySelector('#set-alarm-sound').value;
    try { if (preview) { preview.pause(); } } catch (_) {}
    const a = preview = new Audio('/alarm-' + slug + '.m4a');
    // Playing this may have taken the audio session, which leaves the cached mic silent-but-live, and
    // a mic re-acquired mid-tone takes the session back and cuts the preview. So say when it starts
    // and when it is over; voiceagent re-acquires only after. Only the CURRENT preview says it is over,
    // so the one a second press replaces cannot let the mic in under the next.
    const over = () => { if (preview === a) document.dispatchEvent(new CustomEvent('hub:audioplayed')); };
    ['pause', 'ended', 'error'].forEach((ev) => a.addEventListener(ev, over));
    document.dispatchEvent(new CustomEvent('hub:audioplaying'));
    a.play().catch(over);
  };
  back.querySelector('#set-alarm-sound').addEventListener('change', (e) => {
    save('alarm_sound', e.target.value);
    playTone();
  });
  back.querySelector('#set-alarm-play').addEventListener('click', playTone);
  back.querySelector('#set-tts-voice').addEventListener('change', (e) => save('tts_voice', e.target.value));
  back.querySelector('#set-tts-speed').addEventListener('change', (e) => save('tts_speed', e.target.value));
  back.querySelector('.settings-x').addEventListener('click', close);

  back.querySelector('#set-wf-enabled').addEventListener('click', (e) => {
    const b = e.target.closest('[data-v]'); if (!b) return;
    back.querySelectorAll('#set-wf-enabled button').forEach((x) => x.classList.toggle('on', x === b));
    save('wakefree_enabled', b.dataset.v);   // listener reacts live via realtime → mic handoff
  });
  back.querySelector('#set-inject-mode').addEventListener('click', (e) => {
    const b = e.target.closest('[data-v]'); if (!b) return;
    back.querySelectorAll('#set-inject-mode button').forEach((x) => x.classList.toggle('on', x === b));
    save('voice_inject_mode', b.dataset.v);   // listener: Mac-mic → focused window; Fly server mutes the ESP
  });
  back.querySelector('#set-speak-replies').addEventListener('click', (e) => {
    const b = e.target.closest('[data-v]'); if (!b) return;
    back.querySelectorAll('#set-speak-replies button').forEach((x) => x.classList.toggle('on', x === b));
    save('voice_speak_replies', b.dataset.v);   // listener mirrors → voice-speak flag; Stop hook reads reply aloud
  });
  back.querySelector('#set-push').addEventListener('click', (e) => {
    const b = e.target.closest('[data-v]'); if (!b) return;
    back.querySelectorAll('#set-push button').forEach((x) => x.classList.toggle('on', x === b));
    save('push_enabled', b.dataset.v);          // gates session-reply pushes (notifySessionReply)
  });
  back.querySelector('#set-jaredbot').addEventListener('click', (e) => {
    const b = e.target.closest('[data-v]'); if (!b) return;
    back.querySelectorAll('#set-jaredbot button').forEach((x) => x.classList.toggle('on', x === b));
    save('jaredbot_enabled', b.dataset.v);      // messages-mcp jaredbot.py reads this before every decision
  });
  // Full agent mode — hub and full-agent keep SEPARATE, persistent conversations now, so toggling the mode
  // just switches which one is live; it no longer wipes anything (the worker resumes each mode's own session).
  back.querySelector('#set-agent-mode').addEventListener('click', (e) => {
    const b = e.target.closest('[data-v]'); if (!b) return;
    back.querySelectorAll('#set-agent-mode button').forEach((x) => x.classList.toggle('on', x === b));
    save('agent_mode', b.dataset.v);
  });
  back.querySelector('#set-agent-cwd').addEventListener('change', (e) => save('agent_cwd', e.target.value));
  // Idle reset is shown in minutes but stored in seconds (session_reset_s). No data-key, so the generic
  // positive-number handler below skips it.
  back.querySelector('#set-reset-min').addEventListener('change', (e) => {
    const m = parseInt(e.target.value, 10);
    if (Number.isFinite(m) && m > 0) save('session_reset_s', Math.round(m * 60));
  });
  back.querySelector('#set-veto-kts').addEventListener('change', (e) => {
    const v = parseFloat(e.target.value);
    if (Number.isFinite(v) && v >= 0) save('surf_veto_kts', v);
  });
  back.querySelectorAll('.settings-num').forEach((inp) => {
    inp.addEventListener('change', () => {
      const v = parseFloat(inp.value);
      // `data-min0` lets 0 through, for a field where 0 means none (the watch edge's black band).
      const min = 'min0' in inp.dataset ? 0 : Number.MIN_VALUE;
      if (inp.dataset.key && Number.isFinite(v) && v >= min) save(inp.dataset.key, v);
    });
  });
  back.querySelectorAll('.settings-color').forEach((inp) => {
    inp.addEventListener('change', () => save(inp.dataset.key, inp.value));
  });
  back.querySelector('#set-speech-mode').addEventListener('click', (e) => {
    const b = e.target.closest('[data-v]'); if (!b) return;
    back.querySelectorAll('#set-speech-mode button').forEach((x) => x.classList.toggle('on', x === b));
    save('watch_speech_mode', b.dataset.v);   // read by the watch at the start of each recording
  });
  // Surplus/deficit: signed integer (negative = cut), so it bypasses the positive-only handler above.
  back.querySelector('#set-surplus').addEventListener('change', (e) => {
    let v = parseInt(e.target.value, 10);
    if (!Number.isFinite(v)) return;
    v = Math.max(-1000, Math.min(1000, v));   // clamp out typos (e.g. an accidental extra digit)
    e.target.value = v;
    save('surplus_cal', v);
  });

  back.querySelector('#set-wr-enabled').addEventListener('click', (e) => {
    const b = e.target.closest('[data-v]'); if (!b) return;
    back.querySelectorAll('#set-wr-enabled button').forEach((x) => x.classList.toggle('on', x === b));
    save('weight_reminder_enabled', b.dataset.v);
  });
  const wrTimeRow = back.querySelector('#set-wr-time-row');
  const wrTimeInp = back.querySelector('#set-wr-time');
  back.querySelector('#set-wr-mode').addEventListener('click', (e) => {
    const b = e.target.closest('[data-v]'); if (!b) return;
    back.querySelectorAll('#set-wr-mode button').forEach((x) => x.classList.toggle('on', x === b));
    const dynamic = b.dataset.v === 'dynamic';
    wrTimeRow.classList.toggle('dim', dynamic);   // manual time is irrelevant in dynamic mode
    wrTimeInp.disabled = dynamic;
    save('weight_reminder_mode', b.dataset.v);
  });
  wrTimeInp.addEventListener('change', () => {
    if (/^\d{2}:\d{2}$/.test(wrTimeInp.value)) save('weight_reminder_time', wrTimeInp.value);
  });
}

function row(label, key, val) {
  return '<label class="settings-row"><span>' + label + '</span>' +
    '<input class="settings-num" type="number" min="0.5" step="0.5" inputmode="decimal" data-key="' + key + '" value="' + val + '"></label>';
}
